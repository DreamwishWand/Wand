import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {openCurrentItemDatabase} from '../src/lib/items/public-item-master.ts';

test('native expansion tag selectors and actual historic reward links are distinct from entitlement',async()=>{
  const requests=[];
  const db=await openCurrentItemDatabase('',async url=>{requests.push(url);return new Response(await readFile('static'+url),{status:200});});
  const fields=await db.getFieldRows('nativeExpansion.status');
  assert.equal(fields.length,14197);
  const counts=new Map();
  for(const [,s] of fields)counts.set(s,(counts.get(s)??0)+1);
  assert.equal(counts.get('tagged'),11277);
  assert.equal(counts.get('no_matching_tag'),2559);
  assert.equal(counts.get('unmapped_tag_field'),361);
  const ids=await db.findItemIdsByContent({kind:'native_expansion',expansionKey:'Expansion04'});
  assert.equal(ids.status,'indexed');assert.equal(ids.itemIds.length,849);
  const historical=await db.findItemIdsByContent({kind:'native_expansion_at_introduction',expansionKey:'Expansion04'});
  assert.deepEqual(historical.itemIds,ids.itemIds);
  const [bridge,quest,friend,internal,unknown,duplicate]=await db.getNativeExpansionAffiliations([40006771,40006127,40006689,31300003,99999999,40006127]);
  assert.equal(bridge.expansionKey,'Expansion04');
  assert.equal(bridge.mandatoryTagSelectorIndex,1);
  assert.equal(bridge.sourceVersion,'1.26.1');
  assert.equal(quest.expansionAtIntroduction,'Expansion04');
  assert.equal(friend.expansionKey,'Expansion04');
  assert.equal(internal.status,'unmapped_tag_field');assert.equal(internal.expansionKey,null);
  assert.equal(unknown,null);assert.deepEqual(quest,duplicate);assert(Object.isFrozen(quest));
  const [unconfirmed,questOrigin,friendOrigin]=await db.getItemContentOrigins([40006771,40006127,40006689]);
  assert.equal(unconfirmed.contentReleaseId,null);
  assert.equal(questOrigin.contentReleaseId,'dlc.the-keepsake-sea');
  assert.equal(friendOrigin.contentReleaseId,'dlc.the-keepsake-sea');
  const rewards=await db.getFieldRows('history.corroboratedExpansionRewardEvidence');
  assert.equal(rewards.length,46);
  const questIds=rewards.filter(([,e])=>e.some(x=>x.kind==='quest_configured_loot'));
  const friendIds=rewards.filter(([,e])=>e.some(x=>x.kind==='character_friendship_reward'));
  assert.equal(questIds.length,23);assert.equal(friendIds.length,24);
  assert.equal((await db.findItemIdsByField('history.contentAttributionEvidenceKind',{kind:'equals',value:'verified_expansion_tag_and_reward'})).length,46);
  assert.equal((await db.findItemIdsByContent({kind:'confirmed_release',releaseId:'dlc.the-keepsake-sea'})).itemIds.length,759);
  assert(!requests.some(u=>u.includes('/id/')||u.includes('/locale/')||u.includes('/text/')));
});
